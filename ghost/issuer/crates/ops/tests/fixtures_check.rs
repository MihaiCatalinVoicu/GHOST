//! The committed ops fixtures (`tests/fixtures`: the source of the test schedule and its sealed
//! test keys) and the fixture roots of `scripts/gates/entitlement-schedule.sh`
//! (`test-harness/gates/entitlement-schedule`). Everything derived deterministically is checked
//! byte for byte; the two ignored tests regenerate the files:
//!
//!   cargo test -p ghost-issuer-ops --test fixtures_check -- --ignored write_ops_fixtures
//!   cargo test -p ghost-issuer-ops --test fixtures_check -- --ignored write_gate_fixtures
//!
//! (the gate fixtures copy one sealed key, so write the ops fixtures first).

