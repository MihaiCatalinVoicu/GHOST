//! Regenerates the committed entitlement test fixtures. Both tests are ignored; run them only to
//! rebuild the fixtures, in release mode:
//!
//!   cargo test --release -p ghost-issuer --test fixture_gen -- --ignored generate_test_schedule
//!   GHOST_VECTOR_OUT=<file> cargo test --release -p ghost-issuer --test fixture_gen -- --ignored generate_ghost_vectors
//!
//! `generate_test_schedule` creates fresh RSA-2048 keys (so every later vector changes with it);
//! `generate_ghost_vectors` is deterministic in the committed fixtures and writes the `[ghost]`
//! section of `protocol/test-vectors/blind_rsa_pp2.txt`.

