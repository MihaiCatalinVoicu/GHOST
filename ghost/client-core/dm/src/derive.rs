//! Derivations and typed key inputs (design §3.1, §3.2, §6.3, §6.7, §9.4).
//!
//! Every DM secret derived from the seed is `HKDF-SHA256(ikm = m, salt = ∅, info = label || params,
//! L = 32)` with a label of [`DmLabel`] (prefix `ghost/v1/dm/`); every card-level value is the same
//! with `ikm = card_secret_i` and a label of [`CardLabel`] (prefix `ghost/v1/card/`).
//!
//! **T26 (relay-blind addressing).** No derivation takes a public key, a `ghost1` string or a
//! safety number as its key input. The gate's Rust half is the type system: every `derive_*`
//! function below takes one of the newtypes of this module as its key input, and
//! `derivation_key_inputs_are_typed` pins each signature, so a `&[u8]` overload cannot be added
//! without failing the build.

use hkdf::Hkdf;
use sha2::{Digest, Sha256};
use zeroize::{Zeroize, ZeroizeOnDrop};

/// Length of every derived DM secret.
pub const SECRET_BYTES: usize = 32;

/// Prefix of every seed-level label.
pub const DM_LABEL_PREFIX: &str = "ghost/v1/dm/";
/// Prefix of every card-level label.
pub const CARD_LABEL_PREFIX: &str = "ghost/v1/card/";

macro_rules! secret_newtype {
    ($(#[$meta:meta])* $name:ident) => {
        $(#[$meta])*
        #[derive(Clone, Zeroize, ZeroizeOnDrop)]
        pub struct $name([u8; SECRET_BYTES]);

        impl $name {
            /// Wraps 32 raw bytes as this key kind.
            pub fn from_bytes(bytes: [u8; SECRET_BYTES]) -> Self {
                Self(bytes)
            }

            /// The raw bytes, for the one primitive that consumes this key kind.
            pub fn as_bytes(&self) -> &[u8; SECRET_BYTES] {
                &self.0
            }
        }

        impl core::fmt::Debug for $name {
            fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
                // Secrets never render: a Debug of a key would put it in a panic payload.
                f.write_str(concat!(stringify!($name), "(..)"))
            }
        }
    };
}

secret_newtype!(
    /// The MESSAGING branch `m` of the root entropy (`DerivationLabels.MESSAGING`, Phase 3).
    MessagingBranch
);
secret_newtype!(
    /// `card_secret_i`, the bearer secret of a contact card (§3.3).
    CardSecret
);
secret_newtype!(
    /// A pair root, generated by the recipient of the direction it keys (§6.3).
    PairRoot
);
secret_newtype!(
    /// A pair week key `K_w` (§6.3).
    PairWeekKey
);
secret_newtype!(
    /// The per-session `reply_seed` that provisional mode is keyed from (§6.7).
    ReplySeed
);
secret_newtype!(
    /// An X-Wing shared secret, or an X-Wing decapsulation seed (§9.2).
    KemSecret
);
secret_newtype!(
    /// A secret of the Olm account: the X25519 identity or the unused Ed25519 signing seed (§3.1).
    /// It is an output of this module and never an HKDF key input.
    OlmSecret
);
secret_newtype!(
    /// `session_state_key`: the wrapping key of every persisted DM secret (§2.5).
    StateKey
);

/// `HKDF-SHA256(ikm, salt, info, L = 32)`.
fn hkdf32(ikm: &[u8], salt: Option<&[u8]>, info: &[u8]) -> [u8; SECRET_BYTES] {
    let hkdf = Hkdf::<Sha256>::new(salt, ikm);
    let mut out = [0u8; SECRET_BYTES];
    hkdf.expand(info, &mut out)
        .expect("HKDF-SHA256 with L = 32 is inside the 255 x 32 byte output limit");
    out
}

/// A seed-level label and its parameters (§3.1).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DmLabel {
    /// The Olm identity secret (X25519).
    OlmIdentity,
    /// The Ed25519 seed the Olm account layout requires and that never signs anything.
    OlmAccountSigning,
    /// `card_secret_i` of card index i.
    Card(u16),
    /// The inbox read secret of card index i at the relay of ES slot s.
    InboxRead(u16, u8),
    /// The publication schedule key of card index i.
    Schedule(u16),
}

impl DmLabel {
    /// The label string, without its parameters.
    pub const fn label(self) -> &'static str {
        match self {
            DmLabel::OlmIdentity => "ghost/v1/dm/olm-identity",
            DmLabel::OlmAccountSigning => "ghost/v1/dm/olm-account-signing",
            DmLabel::Card(_) => "ghost/v1/dm/card",
            DmLabel::InboxRead(..) => "ghost/v1/dm/inbox-read",
            DmLabel::Schedule(_) => "ghost/v1/dm/schedule",
        }
    }

    /// The `info` input: the label followed by its parameters, big-endian.
    pub fn info(self) -> Vec<u8> {
        let mut info = self.label().as_bytes().to_vec();
        match self {
            DmLabel::OlmIdentity | DmLabel::OlmAccountSigning => {}
            DmLabel::Card(index) | DmLabel::Schedule(index) => {
                info.extend_from_slice(&index.to_be_bytes())
            }
            DmLabel::InboxRead(index, slot) => {
                info.extend_from_slice(&index.to_be_bytes());
                info.push(slot);
            }
        }
        info
    }

    /// Every seed-level label string.
    pub const LABELS: [&'static str; 5] = [
        "ghost/v1/dm/olm-identity",
        "ghost/v1/dm/olm-account-signing",
        "ghost/v1/dm/card",
        "ghost/v1/dm/inbox-read",
        "ghost/v1/dm/schedule",
    ];
}

/// A card-level label and its parameters (§3.2).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CardLabel {
    /// The inbox namespace `X_i`.
    InboxNamespace,
    /// The bundle namespace `P_i`.
    BundleNamespace,
    /// The deposit secret `D_{i,s}` presented to the relay of ES slot s.
    Deposit(u8),
    /// The bundle fetch secret `RP_{i,s}` presented to the relay of ES slot s.
    BundleRead(u8),
    /// The bundle seal key `KB_i`, which never leaves the device.
    BundleSeal,
    /// The intro outer key `KIO_i`, which never leaves the device.
    IntroOuter,
}

impl CardLabel {
    /// The label string, without its parameters.
    pub const fn label(self) -> &'static str {
        match self {
            CardLabel::InboxNamespace => "ghost/v1/card/inbox-ns",
            CardLabel::BundleNamespace => "ghost/v1/card/bundle-ns",
            CardLabel::Deposit(_) => "ghost/v1/card/deposit",
            CardLabel::BundleRead(_) => "ghost/v1/card/bundle-read",
            CardLabel::BundleSeal => "ghost/v1/card/bundle-seal",
            CardLabel::IntroOuter => "ghost/v1/card/intro-outer",
        }
    }

    /// The `info` input: the label followed by its parameters.
    pub fn info(self) -> Vec<u8> {
        let mut info = self.label().as_bytes().to_vec();
        match self {
            CardLabel::Deposit(slot) | CardLabel::BundleRead(slot) => info.push(slot),
            _ => {}
        }
        info
    }

    /// Every card-level label string.
    pub const LABELS: [&'static str; 6] = [
        "ghost/v1/card/inbox-ns",
        "ghost/v1/card/bundle-ns",
        "ghost/v1/card/deposit",
        "ghost/v1/card/bundle-read",
        "ghost/v1/card/bundle-seal",
        "ghost/v1/card/intro-outer",
    ];
}

/// Label of the pair week key of the base week (§6.3).
pub const PAIR_EPOCH_LABEL: &str = "ghost/v1/dm/pair-epoch";
/// Label of the weekly pair ratchet step (§6.3).
pub const PAIR_NEXT_LABEL: &str = "ghost/v1/dm/pair-next";
/// Label of the provisional key of a direction (§6.7).
pub const PROVISIONAL_LABEL: &str = "ghost/v1/dm/prov";
/// Label and salt prefix of the PQ-C root (§9.4).
pub const PQ_ROOT_LABEL: &str = "ghost/v1/dm/pq-root";
/// Label of the session binding that salts the provisional key (§6.7).
pub const SESSION_BINDING_LABEL: &str = "ghost/v1/dm-session-binding";

/// `oi = HKDF(m, "ghost/v1/dm/olm-identity")` (§3.1). The X25519 secret of the Olm identity.
pub fn derive_olm_identity(m: &MessagingBranch) -> OlmSecret {
    OlmSecret::from_bytes(hkdf32(m.as_bytes(), None, &DmLabel::OlmIdentity.info()))
}

/// `OI`, the X25519 public key of the Olm identity secret. The secret is clamped exactly as
/// X25519 clamps it, so this is the value the bundle publishes and the safety number covers.
pub fn olm_identity_public(secret: &OlmSecret) -> [u8; 32] {
    x25519_dalek::x25519(*secret.as_bytes(), x25519_dalek::X25519_BASEPOINT_BYTES)
}

/// The Ed25519 seed the Olm account layout requires and that never signs anything (§3.1).
pub fn derive_olm_account_signing(m: &MessagingBranch) -> OlmSecret {
    OlmSecret::from_bytes(hkdf32(
        m.as_bytes(),
        None,
        &DmLabel::OlmAccountSigning.info(),
    ))
}

/// `card_secret_i = HKDF(m, "ghost/v1/dm/card" || u16_be(i))` (§3.1).
pub fn derive_card_secret(m: &MessagingBranch, card_index: u16) -> CardSecret {
    CardSecret::from_bytes(hkdf32(
        m.as_bytes(),
        None,
        &DmLabel::Card(card_index).info(),
    ))
}

/// `RX_{i,s}`, the inbox read secret presented to the relay of ES slot s (§3.1).
pub fn derive_inbox_read_secret(
    m: &MessagingBranch,
    card_index: u16,
    slot: u8,
) -> [u8; SECRET_BYTES] {
    hkdf32(
        m.as_bytes(),
        None,
        &DmLabel::InboxRead(card_index, slot).info(),
    )
}

/// `S_i`, the bundle publication schedule key (§3.1, §5.4).
pub fn derive_schedule_key(m: &MessagingBranch, card_index: u16) -> [u8; SECRET_BYTES] {
    hkdf32(m.as_bytes(), None, &DmLabel::Schedule(card_index).info())
}

/// A card-level value of the card secret (§3.2). Namespaces and relay-presented secrets.
pub fn derive_card_value(card_secret: &CardSecret, label: CardLabel) -> [u8; SECRET_BYTES] {
    hkdf32(card_secret.as_bytes(), None, &label.info())
}

/// The inbox namespace `X_i` (§3.2).
pub fn derive_inbox_namespace(card_secret: &CardSecret) -> [u8; SECRET_BYTES] {
    derive_card_value(card_secret, CardLabel::InboxNamespace)
}

/// The bundle namespace `P_i` (§3.2).
pub fn derive_bundle_namespace(card_secret: &CardSecret) -> [u8; SECRET_BYTES] {
    derive_card_value(card_secret, CardLabel::BundleNamespace)
}

/// `K_b = HKDF(root, "ghost/v1/dm/pair-epoch" || u64_be(b))`, the base-week key (§6.3).
pub fn derive_pair_base_week_key(root: &PairRoot, base_week: u64) -> PairWeekKey {
    let mut info = PAIR_EPOCH_LABEL.as_bytes().to_vec();
    info.extend_from_slice(&base_week.to_be_bytes());
    PairWeekKey::from_bytes(hkdf32(root.as_bytes(), None, &info))
}

/// `K_{w+1} = HKDF(K_w, "ghost/v1/dm/pair-next")`, one weekly ratchet step (§6.3).
pub fn derive_pair_next_week_key(week_key: &PairWeekKey) -> PairWeekKey {
    PairWeekKey::from_bytes(hkdf32(
        week_key.as_bytes(),
        None,
        PAIR_NEXT_LABEL.as_bytes(),
    ))
}

/// Direction byte of a provisional key: responder to initiator (§6.7).
pub const PROVISIONAL_DIR_TO_INITIATOR: u8 = 0x01;
/// Direction byte of a provisional key: initiator to responder (§6.7).
pub const PROVISIONAL_DIR_TO_RESPONDER: u8 = 0x02;

/// `sb = SHA-256("ghost/v1/dm-session-binding" || OI_initiator || base_key || F_g || OI_responder)`
/// (§6.7): the salt both sides compute from the Olm session keys they share.
pub fn session_binding(
    oi_initiator: &[u8; 32],
    base_key: &[u8; 32],
    fallback_key: &[u8; 32],
    oi_responder: &[u8; 32],
) -> [u8; SECRET_BYTES] {
    Sha256::new()
        .chain_update(SESSION_BINDING_LABEL.as_bytes())
        .chain_update(oi_initiator)
        .chain_update(base_key)
        .chain_update(fallback_key)
        .chain_update(oi_responder)
        .finalize()
        .into()
}

/// `K_prov(dir) = HKDF(ikm = reply_seed, salt = sb, info = "ghost/v1/dm/prov" || dir)` (§6.7).
pub fn derive_provisional_key(
    reply_seed: &ReplySeed,
    session_binding: &[u8; SECRET_BYTES],
    direction: u8,
) -> [u8; SECRET_BYTES] {
    let mut info = PROVISIONAL_LABEL.as_bytes().to_vec();
    info.push(direction);
    hkdf32(reply_seed.as_bytes(), Some(session_binding), &info)
}

/// The PQ-C root of `seal_root_pq` (§9.4): `HKDF(ikm = root_rand || ss, salt = SHA-256(...))`.
///
/// The salt is `SHA-256("ghost/v1/dm/pq-root" || OI_me || OI_c || u32_be(peer_gen_id) || Q_c || ct)`,
/// so the root is bound to both identities, the generation it was encapsulated to, that
/// generation's public key and the ciphertext that carries it.
pub fn derive_pq_root(
    root_rand: &PairRoot,
    shared_secret: &KemSecret,
    oi_me: &[u8; 32],
    oi_peer: &[u8; 32],
    peer_gen_id: u32,
    peer_xwing_pk: &[u8],
    ciphertext: &[u8],
) -> PairRoot {
    let salt: [u8; 32] = Sha256::new()
        .chain_update(PQ_ROOT_LABEL.as_bytes())
        .chain_update(oi_me)
        .chain_update(oi_peer)
        .chain_update(peer_gen_id.to_be_bytes())
        .chain_update(peer_xwing_pk)
        .chain_update(ciphertext)
        .finalize()
        .into();
    let mut ikm = [0u8; 2 * SECRET_BYTES];
    ikm[..SECRET_BYTES].copy_from_slice(root_rand.as_bytes());
    ikm[SECRET_BYTES..].copy_from_slice(shared_secret.as_bytes());
    let root = PairRoot::from_bytes(hkdf32(&ikm, Some(&salt), PQ_ROOT_LABEL.as_bytes()));
    ikm.zeroize();
    root
}

#[cfg(test)]
mod tests {
    use super::*;

    fn branch() -> MessagingBranch {
        let mut bytes = [0u8; 32];
        for (i, b) in bytes.iter_mut().enumerate() {
            *b = i as u8;
        }
        MessagingBranch::from_bytes(bytes)
    }

    /// The Rust half of gate G-DM3 (T26): every `derive_*` function takes a typed key input, so a
    /// public key or a `ghost1` string cannot be passed as the HKDF key material. The build fails
    /// if a signature changes.
    #[test]
    fn derivation_key_inputs_are_typed() {
        let _: fn(&MessagingBranch) -> OlmSecret = derive_olm_identity;
        let _: fn(&MessagingBranch) -> OlmSecret = derive_olm_account_signing;
        let _: fn(&MessagingBranch, u16) -> CardSecret = derive_card_secret;
        let _: fn(&MessagingBranch, u16, u8) -> [u8; 32] = derive_inbox_read_secret;
        let _: fn(&MessagingBranch, u16) -> [u8; 32] = derive_schedule_key;
        let _: fn(&CardSecret, CardLabel) -> [u8; 32] = derive_card_value;
        let _: fn(&CardSecret) -> [u8; 32] = derive_inbox_namespace;
        let _: fn(&CardSecret) -> [u8; 32] = derive_bundle_namespace;
        let _: fn(&PairRoot, u64) -> PairWeekKey = derive_pair_base_week_key;
        let _: fn(&PairWeekKey) -> PairWeekKey = derive_pair_next_week_key;
        let _: fn(&ReplySeed, &[u8; 32], u8) -> [u8; 32] = derive_provisional_key;
        // `derive_pq_root` (§9.4) takes two typed secrets as key material: the root half and the
        // X-Wing shared secret. Its public-key arguments are salt inputs, never `ikm`.
        let _: DerivePqRoot = derive_pq_root;
    }

    /// The signature of `derive_pq_root`, named so the pin above stays one line.
    type DerivePqRoot =
        fn(&PairRoot, &KemSecret, &[u8; 32], &[u8; 32], u32, &[u8], &[u8]) -> PairRoot;

    #[test]
    fn no_label_is_a_prefix_of_another() {
        let mut labels: Vec<&str> = DmLabel::LABELS.to_vec();
        labels.extend_from_slice(&CardLabel::LABELS);
        labels.push(PAIR_EPOCH_LABEL);
        labels.push(PAIR_NEXT_LABEL);
        labels.push(PROVISIONAL_LABEL);
        labels.push(PQ_ROOT_LABEL);
        labels.push(SESSION_BINDING_LABEL);
        for (i, a) in labels.iter().enumerate() {
            for (j, b) in labels.iter().enumerate() {
                if i != j {
                    assert!(!b.starts_with(a), "{a} is a prefix of {b}");
                }
            }
        }
    }

    #[test]
    fn labels_carry_their_prefix() {
        for label in DmLabel::LABELS {
            assert!(label.starts_with(DM_LABEL_PREFIX), "{label}");
        }
        for label in CardLabel::LABELS {
            assert!(label.starts_with(CARD_LABEL_PREFIX), "{label}");
        }
    }

    #[test]
    fn parameters_separate_outputs() {
        let m = branch();
        let zero = derive_card_secret(&m, 0);
        let one = derive_card_secret(&m, 1);
        assert_ne!(zero.as_bytes(), one.as_bytes());
        assert_ne!(
            derive_inbox_read_secret(&m, 0, 0),
            derive_inbox_read_secret(&m, 0, 1)
        );
        let card = derive_card_secret(&m, 0);
        assert_ne!(
            derive_card_value(&card, CardLabel::Deposit(0)),
            derive_card_value(&card, CardLabel::Deposit(1))
        );
        assert_ne!(
            derive_card_value(&card, CardLabel::BundleSeal),
            derive_card_value(&card, CardLabel::IntroOuter)
        );
    }

    #[test]
    fn pair_ratchet_moves_forward() {
        let root = PairRoot::from_bytes([7u8; 32]);
        let base = derive_pair_base_week_key(&root, 2_870);
        let next = derive_pair_next_week_key(&base);
        assert_ne!(base.as_bytes(), next.as_bytes());
        assert_ne!(
            derive_pair_base_week_key(&root, 2_870).as_bytes(),
            derive_pair_base_week_key(&root, 2_871).as_bytes()
        );
    }

    #[test]
    fn provisional_directions_differ() {
        let seed = ReplySeed::from_bytes([3u8; 32]);
        let sb = session_binding(&[1u8; 32], &[2u8; 32], &[3u8; 32], &[4u8; 32]);
        assert_ne!(
            derive_provisional_key(&seed, &sb, PROVISIONAL_DIR_TO_INITIATOR),
            derive_provisional_key(&seed, &sb, PROVISIONAL_DIR_TO_RESPONDER)
        );
    }

    #[test]
    fn secret_debug_does_not_render_bytes() {
        let secret = CardSecret::from_bytes([9u8; 32]);
        assert_eq!(format!("{secret:?}"), "CardSecret(..)");
    }
}
