/// `K_b = HKDF(root, "ghost/v1/dm/pair-epoch" || u64_be(b))`, the base-week key (§6.3).
pub fn derive_pair_base_week_key(root: &PairRoot, base_week: u64) -> PairWeekKey {
    let mut info = PAIR_EPOCH_LABEL.as_bytes().to_vec();
    info.extend_from_slice(&base_week.to_be_bytes());
    PairWeekKey::from_bytes(hkdf32(root.as_bytes(), None, &info))
}

/// `K_{w+1} = HKDF(K_w, "ghost/v1/dm/pair-next")`, one weekly ratchet step (§6.3).
pub fn derive_pair_next_week_key(week_key: &PairWeekKey) -> PairWeekKey {
    PairWeekKey::from_bytes(hkdf32(
        week_key.as_bytes(),
        None,
        PAIR_NEXT_LABEL.as_bytes(),
    ))
}

/// Direction byte of a provisional key: responder to initiator (§6.7).
pub const PROVISIONAL_DIR_TO_INITIATOR: u8 = 0x01;
/// Direction byte of a provisional key: initiator to responder (§6.7).
pub const PROVISIONAL_DIR_TO_RESPONDER: u8 = 0x02;

/// `sb = SHA-256("ghost/v1/dm-session-binding" || OI_initiator || base_key || F_g || OI_responder)`
/// (§6.7): the salt both sides compute from the Olm session keys they share.
pub fn session_binding(
    oi_initiator: &[u8; 32],
    base_key: &[u8; 32],
    fallback_key: &[u8; 32],
    oi_responder: &[u8; 32],
) -> [u8; SECRET_BYTES] {
    Sha256::new()
        .chain_update(SESSION_BINDING_LABEL.as_bytes())
        .chain_update(oi_initiator)
        .chain_update(base_key)
        .chain_update(fallback_key)
        .chain_update(oi_responder)
        .finalize()
        .into()
}

/// `K_prov(dir) = HKDF(ikm = reply_seed, salt = sb, info = "ghost/v1/dm/prov" || dir)` (§6.7).
pub fn derive_provisional_key(
    reply_seed: &ReplySeed,
    session_binding: &[u8; SECRET_BYTES],
    direction: u8,
) -> [u8; SECRET_BYTES] {
    let mut info = PROVISIONAL_LABEL.as_bytes().to_vec();
    info.push(direction);
    hkdf32(reply_seed.as_bytes(), Some(session_binding), &info)
}

/// The PQ-C root of `seal_root_pq` (§9.4): `HKDF(ikm = root_rand || ss, salt = SHA-256(...))`.
///
/// The salt is `SHA-256("ghost/v1/dm/pq-root" || OI_me || OI_c || u32_be(peer_gen_id) || Q_c || ct)`,
/// so the root is bound to both identities, the generation it was encapsulated to, that
/// generation's public key and the ciphertext that carries it.
pub fn derive_pq_root(
    root_rand: &PairRoot,
    shared_secret: &KemSecret,
    oi_me: &[u8; 32],
    oi_peer: &[u8; 32],
    peer_gen_id: u32,
    peer_xwing_pk: &[u8],
    ciphertext: &[u8],
) -> PairRoot {
    let salt: [u8; 32] = Sha256::new()
        .chain_update(PQ_ROOT_LABEL.as_bytes())
        .chain_update(oi_me)
        .chain_update(oi_peer)
        .chain_update(peer_gen_id.to_be_bytes())
        .chain_update(peer_xwing_pk)
        .chain_update(ciphertext)
        .finalize()
        .into();
    let mut ikm = [0u8; 2 * SECRET_BYTES];
    ikm[..SECRET_BYTES].copy_from_slice(root_rand.as_bytes());
    ikm[SECRET_BYTES..].copy_from_slice(shared_secret.as_bytes());
    let root = PairRoot::from_bytes(hkdf32(&ikm, Some(&salt), PQ_ROOT_LABEL.as_bytes()));
    ikm.zeroize();
    root
}

