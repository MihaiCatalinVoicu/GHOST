/// `HKDF-SHA256(ikm, salt, info, L = 32)`.
fn hkdf32(ikm: &[u8], salt: Option<&[u8]>, info: &[u8]) -> [u8; SECRET_BYTES] {
    let hkdf = Hkdf::<Sha256>::new(salt, ikm);
    let mut out = [0u8; SECRET_BYTES];
    hkdf.expand(info, &mut out)
        .expect("HKDF-SHA256 with L = 32 is inside the 255 x 32 byte output limit");
    out
}

/// A seed-level label and its parameters (§3.1).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DmLabel {
    /// The Olm identity secret (X25519).
    OlmIdentity,
    /// The Ed25519 seed the Olm account layout requires and that never signs anything.
    OlmAccountSigning,
    /// `card_secret_i` of card index i.
    Card(u16),
    /// The inbox read secret of card index i at the relay of ES slot s.
    InboxRead(u16, u8),
    /// The publication schedule key of card index i.
    Schedule(u16),
    /// CO-9's channel self-update schedule key `K_sched` (§6.4 of the Phase 10 design,
    /// owner decision Q-F5-6 of §19.54): `HKDF(m, "ghost/v1/dm/channel-schedule")` — one key
    /// for every channel of the identity, no parameters. Consumed by the channel engine
    /// (`ChannelSchedule`), which is why the label names the channel schedule, not a card.
    ChannelSchedule,
}

impl DmLabel {
    /// The label string, without its parameters.
    pub const fn label(self) -> &'static str {
        match self {
            DmLabel::OlmIdentity => "ghost/v1/dm/olm-identity",
            DmLabel::OlmAccountSigning => "ghost/v1/dm/olm-account-signing",
            DmLabel::Card(_) => "ghost/v1/dm/card",
            DmLabel::InboxRead(..) => "ghost/v1/dm/inbox-read",
            DmLabel::Schedule(_) => "ghost/v1/dm/schedule",
            DmLabel::ChannelSchedule => "ghost/v1/dm/channel-schedule",
        }
    }

    /// The `info` input: the label followed by its parameters, big-endian.
    pub fn info(self) -> Vec<u8> {
        let mut info = self.label().as_bytes().to_vec();
        match self {
            DmLabel::OlmIdentity | DmLabel::OlmAccountSigning | DmLabel::ChannelSchedule => {}
            DmLabel::Card(index) | DmLabel::Schedule(index) => {
                info.extend_from_slice(&index.to_be_bytes())
            }
            DmLabel::InboxRead(index, slot) => {
                info.extend_from_slice(&index.to_be_bytes());
                info.push(slot);
            }
        }
        info
    }

    /// Every seed-level label string.
    pub const LABELS: [&'static str; 6] = [
        "ghost/v1/dm/olm-identity",
        "ghost/v1/dm/olm-account-signing",
        "ghost/v1/dm/card",
        "ghost/v1/dm/inbox-read",
        "ghost/v1/dm/schedule",
        "ghost/v1/dm/channel-schedule",
    ];
}

