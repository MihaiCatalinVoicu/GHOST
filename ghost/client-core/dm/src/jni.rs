/// The TLV field tags of the reply. Kotlin's `DmResult` decodes exactly this set.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum Field {
    /// `ctxOpen`: the context handle, `i64` big-endian.
    Handle = 0x01,
    /// A wrapped `olm_session.state_env`.
    State = 0x02,
    /// A raw 32-byte session id.
    SessionId = 0x03,
    /// Olm message bytes.
    L1 = 0x04,
    /// L0 content bytes.
    L0 = 0x05,
    /// Bit 0: the output is a PreKey message. Bit 1: the session is acknowledged.
    Flags = 0x06,
    /// Which stored slot decrypted: 0 = current, 1 = previous.
    SlotUsed = 0x07,
    /// A wrapped `reply_seed` (`olm_session.prov_env`).
    ReplySeed = 0x08,
    /// A receiver chain's next index, `u64` big-endian.
    ChainIndex = 0x09,
    /// How many skipped keys `sessionPrune` removed, `u32` big-endian.
    Pruned = 0x0a,
    /// The 60 safety-number digits, ASCII.
    Digits = 0x0b,
    /// The 65-byte scannable safety number.
    Scannable = 0x0c,
    /// The own contact card v2, 131 bytes.
    Card = 0x0d,
    /// The inbox namespace `X_i`.
    InboxNamespace = 0x0e,
    /// The bundle namespace `P_i`.
    BundleNamespace = 0x0f,
    /// The recognition key of `KIO_i` (§6.2 rule R-S6).
    RecognitionIntro = 0x10,
    /// The recognition key of `KB_i`.
    RecognitionBundle = 0x11,
    /// The own Olm identity public key.
    OlmIdentity = 0x12,
    /// A sealed blob of a bucket size (here: the 4 KiB bundle).
    Blob = 0x13,
    /// A generation's Olm fallback public key `F_g`.
    FallbackPublic = 0x14,
    /// A generation's X-Wing public key `Q_g`.
    XwingPublic = 0x15,
    /// A wrapped `olm_prekey_gen.secrets_env` (`f_g || q_g seed`).
    GenerationSecrets = 0x16,
    /// The inbox read secret `RX_{i,s}` (§3.1). It is a **bearer** secret: it is presented to the
    /// relay of slot s inside the 67-byte credential v3, so Kotlin holds it in clear (§3.2's last
    /// sentence lists bearer credentials among the three things Kotlin may hold unwrapped).
    ReadSecret = 0x17,
    /// The weekly bundle-publication offset `t_pub(w) − start(w)` in seconds, `u32` big-endian
    /// (§5.4). Derived from the schedule key `S_i`, which itself never leaves the context.
    PublicationOffset = 0x18,
    /// The own deposit secret `D_{i,s}` (§3.2): what the owner registers a verifier for and what
    /// every holder of its card presents to deposit.
    DepositSecret = 0x19,
    /// The own bundle fetch secret `RP_{i,s}` (§3.2), registered as kind FETCH (§22.8.7).
    FetchSecret = 0x1a,
    // ---- added by S7 ----
    /// An Ed25519 `identity_pk`: a card's owner, or a bundle's signer (§3.3, §5.3).
    IdentityPk = 0x1b,
    /// A card index, `u32` big-endian (the card carries a `u16`).
    CardIndex = 0x1c,
    /// A **wrapped** card-derived intro outer key `KIO_c` (rule R-S6: Kotlin never holds it open).
    IntroKey = 0x1d,
    /// A **wrapped** card-derived bundle seal key `KB_c`.
    BundleKey = 0x1e,
    /// A bundle's ISO week, `u64` big-endian (§5.3).
    BundleWeek = 0x1f,
    /// A bundle's rank inside its week, `u32` big-endian (§5.3).
    BundleRank = 0x20,
    /// A bundle generation id, `u32` big-endian.
    GenId = 0x21,
    /// An Olm PreKey message's base key (§3.4).
    BaseKey = 0x22,
    /// An Olm PreKey message's one-time (here: fallback) key (§6.5 step 4).
    OneTimeKey = 0x23,
    /// An Olm message's receiver-chain ratchet key, for the peek order and the gap hold (§7.7).
    RatchetKey = 0x24,
    /// The packed pair-week keys of `pairKeys`: `u32_be(count) || (u64_be(week) ||
    /// u32_be(len) || open_env || recog_key(32))*` (§6.3).
    PairKeys = 0x25,
    /// A binding minute, `u32` big-endian (§3.4).
    BindingMinute = 0x26,
    /// An L0 `message_id` (§7.1).
    MessageId = 0x27,
    /// An L0 `author_minute`, `u32` big-endian.
    AuthorMinute = 0x28,
    /// An L0 `minute_index`, `u32` big-endian (the field is a `u16`).
    MinuteIndex = 0x29,
    /// An L0 `timer_code`, one byte.
    TimerCode = 0x2a,
    /// An L0 `timer_version`, `u32` big-endian.
    TimerVersion = 0x2b,
    /// An L0 `quote_ref`: 16 bytes, or absent when the message quotes nothing.
    QuoteRef = 0x2c,
    /// An L0 body.
    Body = 0x2d,
    /// An L0 `kind`, one byte (§7.1).
    ContentKind = 0x2e,
    /// Which TLVs an L0 carried: bit 0 `seal_root`, bit 1 `session_reset`, bit 2 `revocation`,
    /// bit 3 a PQ-C TLV (`seal_root_pq` or `pq_key`), which Phase 9 counts and ignores (§9.4).
    TlvFlags = 0x2f,
    /// A `seal_root` generation number, `u32` big-endian (the field is a `u16`).
    RootGen = 0x30,
    /// A `seal_root` base week, `u64` big-endian.
    BaseWeek = 0x31,
    /// A **wrapped** pair root (`dm_pair_offer.root_env`).
    PairRootEnv = 0x32,
    /// A **wrapped** offered TLV value (`dm_pair_offer.offer_env`).
    PairOfferEnv = 0x33,
    /// A revocation certificate v2 carried by TLV 0x0003 (§8.5).
    Revocation = 0x34,
    /// A **wrapped** provisional opening key this device seals with (§6.7).
    ProvisionalOutEnv = 0x35,
    /// A **wrapped** provisional opening key this device opens the peer's envelopes with.
    ProvisionalInEnv = 0x36,
    /// The recognition key of [`Field::ProvisionalOutEnv`] (rule R-S6).
    RecognitionProvOut = 0x37,
    /// The recognition key of [`Field::ProvisionalInEnv`].
    RecognitionProvIn = 0x38,
    /// The direction byte of [`Field::ProvisionalOutEnv`], one byte (§6.7).
    ///
    /// It crosses because it is part of that envelope's **binding**: the caller hands it back to
    /// `sealSym` unchanged, and computing it in Kotlin would be protocol logic ADR-19 puts in
    /// Rust. Which of the two directions this device seals with follows from the session's own
    /// keys, so no caller decides it.
    ProvisionalOutDirection = 0x39,
    /// The direction byte of [`Field::ProvisionalInEnv`], one byte.
    ProvisionalInDirection = 0x3a,
    /// The bucket rule R-B1 chose for an `l0Encode` record, `u32` big-endian (§6.6).
    ///
    /// It crosses so that the bucket is a function of the **body length** computed by the code
    /// that owns the rule: a Kotlin caller that derived it from the encoded L0 or from the
    /// ciphertext would be mutants ME-22 and ME-3, and nothing in the engine would catch it.
    Bucket = 0x3b,
    // ---- added by S8 ----
    /// A revocation certificate v2's `issued_minute`, `u32` big-endian (§8.5; T13 makes the
    /// minute the finest time any DM byte carries).
    IssuedMinute = 0x3c,
    /// A revocation certificate v2's reason code, one byte.
    RevocationReason = 0x3d,
    // ---- added by S13 ----
    /// The generation of **mine** a received `seal_root_pq` was encapsulated to, `u32` big-endian
    /// (§9.4): the row the caller loads for [`pq_root_open`].
    PeerGenId = 0x3e,
    /// A received `seal_root_pq` value, 1 166 bytes (§7.1): `root_rand || base_week || root_gen ||
    /// peer_gen_id || xwing_ct`. `root_rand` alone keys nothing (§9.4), and the L0 it came out of
    /// was already on the caller's side of the boundary.
    SealRootPqTlv = 0x3f,
}

