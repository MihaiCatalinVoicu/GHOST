        $crate::export_jni!(@one safetyNumber safety_number);
        $crate::export_jni!(@one chainPosition chain_position);
        $crate::export_jni!(@one sessionPrune session_prune);
        $crate::export_jni!(@one cardParse card_parse);
        $crate::export_jni!(@one cardDerive card_derive);
        $crate::export_jni!(@one bundleOpen bundle_open);
        $crate::export_jni!(@one sealIntro seal_intro);
