/// The secrets the DM context derives once at unlock and holds in native memory only.
struct DmContext {
    olm_identity: OlmSecret,
    olm_signing: OlmSecret,
    state_key: StateKey,
    /// The branch the card, namespace and read secrets derive from (§3.1).
    messaging: MessagingBranch,
    /// The `ghost1` Ed25519 seed, handed over by `:identity` at unlock (§2.4, X-21).
    identity_seed: IdentitySeed,
}

fn registry() -> &'static Mutex<HashMap<i64, DmContext>> {
    static REGISTRY: OnceLock<Mutex<HashMap<i64, DmContext>>> = OnceLock::new();
    REGISTRY.get_or_init(|| Mutex::new(HashMap::new()))
}

/// The registry guard, **recovered from poisoning**.
///
/// [`with_context`] holds this guard across the call body, so a panic caught by [`guarded`] —
/// the `INTERNAL` of §2.6, which S0′ V-5 saw a libcrux panic produce — unwinds through it and
/// poisons the mutex. Treating that as an error would make every later call, `ctxOpen` and
/// `ctxClose` included, report `INTERNAL` for the life of the process: the crash loop §2.7
/// forbids, and a context that lock and wipe can never close or zeroise (§2.5). The map itself
/// cannot be left half-written by such a panic — the body receives `&DmContext` and inserts and
/// removes happen with no user code under the guard — so the recovered contents are sound.
fn registry_lock() -> MutexGuard<'static, HashMap<i64, DmContext>> {
    registry().lock().unwrap_or_else(PoisonError::into_inner)
}

fn next_handle() -> i64 {
    static NEXT: AtomicI64 = AtomicI64::new(1);
    NEXT.fetch_add(1, Ordering::Relaxed)
}

/// Registers a context and returns its handle.
fn insert_context(context: DmContext) -> i64 {
    let handle = next_handle();
    registry_lock().insert(handle, context);
    handle
}

/// Runs `body` with the named context, or reports [`DmCode::CryptoUnavailable`] for a closed or
/// foreign handle (§2.5).
///
/// The guard is held across the body on purpose: the alternative is to copy the context's secrets
/// out of the map, and DM calls arrive on one actor thread (§2.7), so nothing waits on it. What
/// the guard must not do is latch a panic, which is [`registry_lock`]'s job.
fn with_context<T>(
    handle: jlong,
    body: impl FnOnce(&DmContext) -> Result<T, DmCode>,
) -> Result<T, DmCode> {
    let guard = registry_lock();
    let context = guard.get(&handle).ok_or(DmCode::CryptoUnavailable)?;
    body(context)
}

pub(crate) fn quiet_panics() {
    static QUIET: Once = Once::new();
    QUIET.call_once(|| std::panic::set_hook(Box::new(|_| {})));
}

/// Runs a JNI body and turns its outcome into the reply array. A panic becomes `INTERNAL`; a
/// failure to allocate the reply array leaves a null return, which Kotlin reads as `INTERNAL`.
fn guarded(
    env: &mut JNIEnv,
    body: impl FnOnce(&mut JNIEnv) -> Result<Vec<u8>, DmCode>,
) -> jbyteArray {
    quiet_panics();
    let reply = match catch_unwind(AssertUnwindSafe(|| body(env))) {
        Ok(Ok(bytes)) => bytes,
        Ok(Err(code)) => code_only(code),
        Err(_) => code_only(DmCode::Internal),
    };
    match env.byte_array_from_slice(&reply) {
        Ok(array) => array.into_raw(),
        Err(_) => std::ptr::null_mut(),
    }
}

/// The native copy of a Java byte array, **erased when it is dropped**.
///
/// `convert_byte_array` allocates a `Vec` on the native heap and copies the array into it. Some of
/// those arrays are the crown jewels — `ctxOpen`'s MESSAGING branch, `ghost1` seed and
/// `session_state_key`, and every L0 plaintext `encrypt` is handed — so the copy is a
/// [`Zeroizing`] rather than a plain `Vec`: without it the secrets survived `ctxClose` in freed
/// native memory, which §2.5 and L7-D19 ("zeroised on lock and wipe") do not allow (review round
/// 2, R2-04). The rest of the crate already erases every intermediate it builds; this is the copy
/// the boundary itself makes.
fn bytes(env: &JNIEnv, array: &JByteArray) -> Result<Zeroizing<Vec<u8>>, DmCode> {
    env.convert_byte_array(array)
        .map(Zeroizing::new)
        .map_err(|_| DmCode::NonCanonical)
}

/// The same copy, as a fixed-size array: the [`Zeroizing`] temporary erases itself at the end of
/// the statement, so a secret of known length leaves nothing behind either.
fn fixed<const N: usize>(env: &JNIEnv, array: &JByteArray) -> Result<[u8; N], DmCode> {
    bytes(env, array)?
        .as_slice()
        .try_into()
        .map_err(|_| DmCode::NonCanonical)
}

fn day(today: jint) -> Result<u32, DmCode> {
    u32::try_from(today).map_err(|_| DmCode::NonCanonical)
}

